#!/usr/bin/env python3
"""Generates exp_data.h, exp_gen_names.c, exp_gen_ords.c from tools/combase_exports.json (Win10 export table)."""
import json, os, re, collections
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
cb = json.load(open(f'{root}/tools/combase_exports.json'))
ole = json.load(open(f'{root}/tools/ole32_exports.json'))
oa = json.load(open(f'{root}/tools/oleaut32_exports.json'))
byname = {x['name']: x for x in cb if x['name']}
byord = {x['ordinal']: x for x in cb}
here = os.path.dirname(os.path.abspath(__file__))

h = ['/* GENERATED by gen.py from tools/combase_exports.json - do not edit. */',
     'struct cbexp { const char *name; unsigned ord; unsigned rva; };',
     'struct fwd { const char *name; const char *target; unsigned tord; };',
     f'#define CB_NEXPORTS {len(cb)}',
     'static const struct cbexp cb_all[] = {']
for x in sorted(cb, key=lambda x: x['ordinal']):
    n = '"%s"' % x['name'] if x['name'] else 'NULL'
    h.append(f'  {{ {n}, {x["ordinal"]}, {x["rva"]}u }},')
h.append('};')

def fwdtable(tab, items):
    h.append(f'static const struct fwd {tab}[] = {{')
    for name, tgt, tord in items:
        t = '"%s"' % tgt if tgt else 'NULL'
        h.append(f'  {{ "{name}", {t}, {tord} }},')
    h.append('};')
    h.append(f'#define {tab.upper()}_N (sizeof({tab})/sizeof({tab}[0]))')

def collect(lst):
    direct, byo = [], []
    for x in lst:
        f = x['forwarder']
        if not f or not x['name']: continue
        mod, tgt = f.split('.', 1)
        base = mod.lower()
        if not (base == 'combase' or (base.startswith('api-ms-win-core-com'))): continue
        if tgt.startswith('#'):
            if base == 'combase': byo.append((x['name'], None, int(tgt[1:])))
        elif tgt in byname:
            direct.append((x['name'], tgt, 0))
    return direct, byo
d, o = collect(ole)
fwdtable('ole_fwd_name', d); fwdtable('ole_fwd_ord', o)
d2, _ = collect(oa)
fwdtable('oa_fwd_name', d2)
open(f'{here}/exp_data.h', 'w').write('\n'.join(h) + '\n')

# bucketed per-name tests
names = sorted((x for x in cb if x['name']), key=lambda x: x['name'])
def bucket(lst, n):
    return [lst[i:i+n] for i in range(0, len(lst), n)]
out = ['/* GENERATED by gen.py - do not edit. Table-driven export resolution tests for combase.dll. */',
       '#define EXP_WINE_TOLERANT', '#include "exp_common.h"', '']
for i, b in enumerate(bucket(names, 8)):
    out.append(f'/* {b[0]["name"]} .. {b[-1]["name"]} */')
    out.append(f'TEST(exports_combase_name_{i:03d}) {{')
    out.append('    static const char *const n[] = { %s };' % ', '.join('"%s"' % x['name'] for x in b))
    out.append('    exp_check_names(n, sizeof n / sizeof n[0]);')
    out.append('}')
open(f'{here}/exp_gen_names.c', 'w').write('\n'.join(out) + '\n')

# per-ordinal-range tests (all ordinals, named and unnamed)
out = ['/* GENERATED by gen.py - do not edit. Ordinal resolution tests for combase.dll. */',
       '#define EXP_WINE_TOLERANT', '#include "exp_common.h"', '']
for i, b in enumerate(bucket(sorted(cb, key=lambda x: x['ordinal']), 16)):
    out.append(f'TEST(exports_combase_ord_{b[0]["ordinal"]:03d}_{b[-1]["ordinal"]:03d}) {{ exp_check_ord_range({b[0]["ordinal"]}, {b[-1]["ordinal"]}); }}')
open(f'{here}/exp_gen_ords.c', 'w').write('\n'.join(out) + '\n')
print(len(cb), len(d), len(o), len(d2))
