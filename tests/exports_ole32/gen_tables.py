#!/usr/bin/env python3
"""Regenerates exp_table.h and the forwarder table in exports_forwarders.c from tools/*_exports.json.
Run from anywhere:  python3 tests/exports_ole32/gen_tables.py"""
import json, os, re, collections
here = os.path.dirname(os.path.abspath(__file__))
tools = os.path.join(here, '..', '..', 'tools')
d = sorted(json.load(open(os.path.join(tools, 'ole32_exports.json'))), key=lambda e: e['ordinal'])
cb = json.load(open(os.path.join(tools, 'combase_exports.json')))
names = {e['name'] for e in d if e['name']}
cbonly = sorted(e['name'] for e in cb if e['name'] and e['name'] not in names)
def cs(s): return 'NULL' if s is None else '"%s"' % s
o = ['/* GENERATED by gen_tables.py from tools/ole32_exports.json (Windows 10 x64 ole32.dll). Do not edit. */',
     'struct exp_ent { const char *name; unsigned ord; const char *fwd; };',
     'static const struct exp_ent g_exp[] = {']
for e in d:
    o.append('  { %s, %d, %s },' % (cs(e['name']), e['ordinal'], cs(e['forwarder'])))
o.append('};')
o.append('#define EXP_N (sizeof g_exp / sizeof g_exp[0])')
o.append('#define EXP_ORD_BASE %d' % d[0]['ordinal'])
o.append('#define EXP_ORD_MAX %d' % d[-1]['ordinal'])
o.append('#define EXP_NAMED %d' % len(names))
o.append('/* names exported by combase.dll but NOT by ole32.dll */')
o.append('static const char *const g_cbonly[] = {')
for n in cbonly: o.append('  "%s",' % n)
o.append('};')
o.append('#define CBONLY_N (sizeof g_cbonly / sizeof g_cbonly[0])')
open(os.path.join(here, 'exp_table.h'), 'w').write('\n'.join(o) + '\n')
# forwarder doc table
groups = collections.OrderedDict()
for e in d:
    if e['forwarder']:
        groups.setdefault(e['forwarder'].split('.')[0].lower(), []).append(e)
t = ['/* BEGIN FWDTABLE (generated) */', '/*']
for g, es in sorted(groups.items()):
    t.append(' * forwarded to %s (%d):' % (g, len(es)))
    line = ' *  '
    for e in es:
        tgt = e['forwarder'].split('.', 1)[1]
        item = ' %s' % e['name'] + ('' if tgt == e['name'] else '->%s' % tgt) + ','
        if len(line) + len(item) > 100: t.append(line); line = ' *  '
        line += item
    t.append(line.rstrip(','))
t.append(' */'); t.append('/* END FWDTABLE */')
p = os.path.join(here, 'exports_forwarders.c')
s = open(p).read()
s = re.sub(r'/\* BEGIN FWDTABLE.*?/\* END FWDTABLE \*/', lambda m: '\n'.join(t), s, flags=re.S)
open(p, 'w').write(s)
